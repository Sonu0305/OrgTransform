def persistent_payload() -> dict:
    return {payload_key: deepcopy(globals()[global_key]) for payload_key, global_key in PERSISTED_COLLECTIONS.items()}


def persist() -> None:
    DATA_FILE.parent.mkdir(parents=True, exist_ok=True)
    temp_file = DATA_FILE.with_suffix(".tmp")
    temp_file.write_text(json.dumps(persistent_payload(), indent=2), encoding="utf-8")
    temp_file.replace(DATA_FILE)


def load_persistent_data() -> None:
    if not DATA_FILE.exists():
        persist()
        return

    try:
        stored = json.loads(DATA_FILE.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        backup_file = DATA_FILE.with_suffix(".invalid.json")
        DATA_FILE.replace(backup_file)
        persist()
        return

    changed = False
    for payload_key, global_key in PERSISTED_COLLECTIONS.items():
        if payload_key in stored:
            globals()[global_key] = stored[payload_key]
        else:
            stored[payload_key] = deepcopy(globals()[global_key])
            changed = True

    if changed:
        persist()


